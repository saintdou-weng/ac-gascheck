const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'gc-item-page.js'), 'utf8');
const ctx = { window: {}, document: { getElementById(){ return null; }, createElement(){ return { style:{}, setAttribute(){} }; }, head:{ appendChild(){} } }, localStorage: { getItem(){ return ''; }, setItem(){} }, console };
ctx.window = ctx; vm.createContext(ctx);
new vm.Script(src, { filename:'gc-item-page.js' }).runInContext(ctx);
assert(ctx.GC && ctx.GC.ItemPage && typeof ctx.GC.ItemPage.create === 'function');
const items = [{ id:'a1', name:'Fridge', photo:'' }, { id:'a2', name:'TV', photo:'data:image/png;base64,AA' }];
const ip = ctx.GC.ItemPage.create({ key:'t', list:() => items, id:x => x.id, row:x => ({ photo:x.photo, code:x.id, title:x.name, sub:'<b>s</b>' }) });
['open','close','refresh','isOpen','listHtml','bindList','kv','kpis'].forEach(k => assert.strictEqual(typeof ip[k], 'function', k));
const html = ip.listHtml(items);
assert.strictEqual((html.match(/class="gip-row"/g) || []).length, 2, 'one row per item');
assert(html.includes('gip-th empty'), 'missing photo keeps a dashed placeholder');
assert(html.includes('<img class="gip-th"'), 'photo thumbnail shown');
assert(ip.listHtml([]).includes('gip-empty'));
assert(ip.kv([['A', ''], ['B', '<x>']]).includes('&lt;x&gt;'), 'values escaped');
const asset = fs.readFileSync(path.join(root, 'ac_gascheck_asset_v2.html'), 'utf8');
assert(asset.includes('gc-item-page.js?v=20261122a'));
assert(/window\.openDetail=function/.test(asset), 'Detail opens the item page');
assert(/window\.renderCards=function/.test(asset), 'phone cards become one row per item');
['quickSt(a.code','openEdit(a.code)','openPrintSingle(a.code)',"openReq('transfer'","openReq('disposal'",'deleteAssetRow(a.code)','saveToGAS()'].forEach(k => assert(asset.includes(k), 'asset uses original function ' + k));
const key = fs.readFileSync(path.join(root, 'ac_gascheck_keymovement_v2.html'), 'utf8');
assert(key.includes('gc-item-page.js?v=20261122a'));
assert(key.includes('listView:masterListView') && key.includes('lend:lendMaster'));
assert(key.includes('window.__keyIpAfterRender'));
['keyMasterOpen(m.id)','keyMasterDelete(m.id)','setReturnNow(','editRecord(id)'].forEach(k => assert(key.includes(k), 'key uses original function ' + k));
assert(/\.modal-overlay\{display:none;position:fixed/.test(key), 'key edit modal is an overlay');
console.log('item_page_1122 ok');
